// Pre-renders the Black Friday 2026 email countdown's text as alpha masks, so the server draws the GIF
// with no font engine at runtime. Writes src/countdown/glyphs.generated.ts (committed).
//
// Re-run after changing a word, a size or a font:
//   npm run countdown:glyphs
// It needs network access (Anton and Inter load from Google Fonts; both are SIL OFL) and a Chromium.
// To use an installed Chrome instead of a Playwright download:
//   PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" npm run countdown:glyphs
import { writeFile } from 'node:fs/promises';
import { deflateRawSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { GLYPH_SPECS, type GlyphSpec } from '../src/countdown/glyph-specs.js';

const out = fileURLToPath(new URL('../src/countdown/glyphs.generated.ts', import.meta.url));
const fontsCss = 'https://fonts.googleapis.com/css2?family=Anton&family=Inter:wght@700&display=block';

interface Raster { w: number; h: number; dx: number; dy: number; advance: number; alpha: number[] }

const browser = await chromium.launch({
  ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH
    ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}),
});
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  await page.setContent(`<!doctype html><link rel="stylesheet" href="${fontsCss}"><body></body>`, { waitUntil: 'networkidle' });
  const rasters = await page.evaluate(async (specs: GlyphSpec[]) => {
    for (const spec of specs) {
      const font = `${spec.weight} ${spec.size}px ${spec.family}`;
      const faces = await document.fonts.load(font, spec.text);
      if (faces.length === 0 || !document.fonts.check(font, spec.text)) throw new Error(`Font did not load: ${font}`);
    }
    return specs.map(spec => {
      const font = `${spec.weight} ${spec.size}px ${spec.family}`;
      const probe = document.createElement('canvas').getContext('2d')!;
      probe.font = font;
      probe.letterSpacing = `${spec.letterSpacing}px`;
      const metrics = probe.measureText(spec.text);
      const pad = Math.ceil(spec.size / 2);
      const canvas = document.createElement('canvas');
      canvas.width = Math.ceil(metrics.width + metrics.actualBoundingBoxLeft + pad * 2);
      canvas.height = Math.ceil(spec.size * 2 + pad * 2);
      const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
      ctx.font = font;
      ctx.letterSpacing = `${spec.letterSpacing}px`;
      ctx.textBaseline = 'alphabetic';
      ctx.fillStyle = '#fff';
      const originX = pad, baseline = Math.ceil(spec.size * 1.4) + pad;
      ctx.fillText(spec.text, originX, baseline);
      const { data, width, height } = ctx.getImageData(0, 0, canvas.width, canvas.height);
      let left = width, right = -1, top = height, bottom = -1;
      for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
        if (data[(y * width + x) * 4 + 3]! > 0) {
          if (x < left) left = x; if (x > right) right = x; if (y < top) top = y; if (y > bottom) bottom = y;
        }
      }
      if (right < 0) throw new Error(`Nothing drawn for ${spec.id}`);
      if (left === 0 || top === 0 || right === width - 1 || bottom === height - 1) throw new Error(`Clipped: ${spec.id}`);
      const w = right - left + 1, h = bottom - top + 1, alpha: number[] = [];
      for (let y = top; y <= bottom; y++) for (let x = left; x <= right; x++) alpha.push(data[(y * width + x) * 4 + 3]!);
      // The trailing letter spacing Chrome adds after the last character is not part of the advance.
      const advance = metrics.width - (spec.text.length > 1 ? spec.letterSpacing : 0);
      return { w, h, dx: left - originX, dy: top - baseline, advance, alpha };
    });
  }, [...GLYPH_SPECS] as GlyphSpec[]);

  const lines = (rasters as Raster[]).map((raster, i) => {
    const spec = GLYPH_SPECS[i]!;
    const data = deflateRawSync(Buffer.from(raster.alpha), { level: 9 }).toString('base64');
    return `  ${JSON.stringify(spec.id)}: { w: ${raster.w}, h: ${raster.h}, dx: ${raster.dx}, dy: ${raster.dy}, advance: ${Math.round(raster.advance * 100) / 100}, data: ${JSON.stringify(data)} },`;
  });
  const source = `// Generated by scripts/generate-countdown-glyphs.ts from src/countdown/glyph-specs.ts. Do not edit by hand.
// Re-run: npm run countdown:glyphs (see the script header). Anton and Inter are SIL Open Font License fonts.
// Each mask is raw-deflated 8-bit coverage, w x h, row-major. dx/dy place the mask's top-left corner
// relative to the pen origin on the baseline; advance is the pen advance without trailing letter spacing.
import type { GlyphId } from './glyph-specs.js';

export interface GlyphRecord { w: number; h: number; dx: number; dy: number; advance: number; data: string }

export const GLYPHS: Record<GlyphId, GlyphRecord> = {
${lines.join('\n')}
};
`;
  await writeFile(out, source);
  console.log(`Wrote ${GLYPH_SPECS.length} masks to src/countdown/glyphs.generated.ts (${source.length} bytes).`);
} finally {
  await browser.close();
}
